#!/bin/sh
. "$(dirname "$0")/common.sh"
echo "== binary =="
echo "$TELEGRAF"
ls -lh "$TELEGRAF"
echo
echo "== telegraf version =="
"$TELEGRAF" version
echo
echo "== telegraf --help (full) =="
"$TELEGRAF" --help
echo
echo "== plugin counts from the binary itself =="
echo "inputs:  $("$TELEGRAF" --input-list 2>/dev/null | wc -l) lines of --input-list"
echo "outputs: $("$TELEGRAF" --output-list 2>/dev/null | wc -l) lines of --output-list"
echo
echo "== a sample config, generated by the tool (first 25 lines) =="
"$TELEGRAF" config create --input-filter cpu:mem --output-filter file 2>/dev/null | head -25
echo
echo "== one plugin's own sample settings: telegraf --usage cpu (first 14 lines) =="
"$TELEGRAF" --usage cpu 2>/dev/null | head -14
